/** STCW / MLC 2006 hours-of-rest rules, computed on-device (no AI). */
export type RestLog = { type: "work" | "rest"; timestamp: string };
export const REST_STORAGE_KEY = "seaminds_rest_logs";
type Seg = { type: "work" | "rest"; start: number; end: number };

/** Work/rest segments clipped to [from, to]. Time before the first log is unknown and ignored. */
export const segments = (logs: RestLog[], from: number, to: number): Seg[] => {
  const sorted = [...logs].sort((a, b) => +new Date(a.timestamp) - +new Date(b.timestamp));
  const out: Seg[] = [];
  sorted.forEach((l, i) => {
    const s = Math.max(+new Date(l.timestamp), from);
    const e = Math.min(i + 1 < sorted.length ? +new Date(sorted[i + 1].timestamp) : to, to);
    if (e > s) out.push({ type: l.type, start: s, end: e });
  });
  return out;
};

const H = 3600000;
const round1 = (ms: number) => Math.round((ms / H) * 10) / 10;

export const restHoursIn = (logs: RestLog[], from: number, to: number) =>
  round1(segments(logs, from, to).filter((s) => s.type === "rest").reduce((t, s) => t + s.end - s.start, 0));

/** Rest periods in a window, merging adjacent rest segments. */
export const restPeriods = (logs: RestLog[], from: number, to: number) => {
  const p: number[] = [];
  let last: Seg | null = null;
  for (const s of segments(logs, from, to)) {
    if (s.type !== "rest") { last = s; continue; }
    if (last?.type === "rest" && last.end === s.start) p[p.length - 1] += s.end - s.start;
    else p.push(s.end - s.start);
    last = s;
  }
  return p.map(round1);
};

export type RestCheck = { rest24: number; rest7d: number; issues: string[] };
/** STCW A-VIII/1 & MLC 2006: ≥10h rest in any 24h, ≥77h in any 7 days, at most 2 rest periods with one ≥6h. */
export const checkRest = (logs: RestLog[], now = Date.now()): RestCheck => {
  const rest24 = restHoursIn(logs, now - 24 * H, now);
  const rest7d = restHoursIn(logs, now - 168 * H, now);
  const issues: string[] = [];
  if (!logs.length) return { rest24, rest7d, issues };
  if (rest24 < 10) issues.push(`Only ${rest24}h rest in the last 24h — minimum is 10h.`);
  if (rest7d < 77) issues.push(`Only ${rest7d}h rest in the last 7 days — minimum is 77h.`);
  const periods = restPeriods(logs, now - 24 * H, now);
  if (periods.length > 2) issues.push(`Rest was split into ${periods.length} periods in 24h — maximum is 2.`);
  if (periods.length > 0 && rest24 >= 10 && Math.max(...periods) < 6) issues.push("No rest period of at least 6h in the last 24h.");
  return { rest24, rest7d, issues };
};

/** Monthly record of hours of rest (one row per calendar day) as CSV. */
export const monthCsv = (logs: RestLog[], year: number, month: number, name = "") => {
  const days = new Date(year, month + 1, 0).getDate();
  const rows = [`Record of hours of rest${name ? " — " + name : ""},${year}-${String(month + 1).padStart(2, "0")}`, "Date,Work hours,Rest hours,10h rule"];
  for (let d = 1; d <= days; d++) {
    const a = +new Date(year, month, d), b = +new Date(year, month, d + 1);
    const segs = segments(logs, a, b);
    if (!segs.length) { rows.push(`${year}-${String(month + 1).padStart(2, "0")}-${String(d).padStart(2, "0")},,,no record`); continue; }
    const rest = restHoursIn(logs, a, b);
    const work = round1(segs.filter((s) => s.type === "work").reduce((t, s) => t + s.end - s.start, 0));
    rows.push(`${year}-${String(month + 1).padStart(2, "0")}-${String(d).padStart(2, "0")},${work},${rest},${rest >= 10 ? "OK" : "CHECK"}`);
  }
  rows.push("", "Generated by SeaMinds from the seafarer's own log. Personal record, not an official ship record.");
  return rows.join("\n");
};
